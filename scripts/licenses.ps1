# Writes licenses/rust-crates.txt: the license text of every Rust crate linked into the exe.
# Crates that share a text are listed together, which keeps the file readable.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$registry = Get-ChildItem "$env:USERPROFILE\.cargo\registry\src" -Directory | Select-Object -First 1
$lines = cargo tree --manifest-path "$root\Cargo.toml" -e normal --target x86_64-pc-windows-msvc --prefix none --format '{p}|{l}' | Sort-Object -Unique
$texts = @{}
$bare = New-Object Collections.ArrayList
foreach ($line in $lines) {
    if ($line -notmatch '^(\S+) v(\S+).*\|(.*)$') { continue }
    $name, $version, $license = $Matches[1], $Matches[2], ($Matches[3] -replace ' \(\*\)$', '')
    if ($name -eq 'screen-translate') { continue }
    $dir = Join-Path $registry.FullName "$name-$version"
    $files = @(Get-ChildItem $dir -File -ErrorAction SilentlyContinue | Where-Object { $_.Name -match '^(licen[sc]e|copying|notice|unlicense)' })
    if ($files.Count -eq 0) {
        if (-not $bare.Contains("$name $version ($license)")) { [void]$bare.Add("$name $version ($license)") }
        continue
    }
    foreach ($file in $files) {
        $text = ([IO.File]::ReadAllText($file.FullName) -replace "`r`n", "`n").Trim()
        if (-not $texts.ContainsKey($text)) { $texts[$text] = New-Object Collections.ArrayList }
        [void]$texts[$text].Add("$name $version ($license)")
    }
}
$out = New-Object Text.StringBuilder
[void]$out.AppendLine('Rust crates linked into screen-translate.exe, with their license texts.')
[void]$out.AppendLine('Generated by scripts/licenses.ps1.')
[void]$out.AppendLine()
foreach ($entry in ($texts.GetEnumerator() | Sort-Object { $_.Value[0] })) {
    [void]$out.AppendLine('=' * 78)
    foreach ($crate in ($entry.Value | Sort-Object -Unique)) { [void]$out.AppendLine($crate) }
    [void]$out.AppendLine('-' * 78)
    [void]$out.AppendLine($entry.Key)
    [void]$out.AppendLine()
}
if ($bare.Count -gt 0) {
    [void]$out.AppendLine('=' * 78)
    [void]$out.AppendLine('These crates ship no license file. See rten.txt and webview2-rs.txt beside this file.')
    foreach ($crate in $bare) { [void]$out.AppendLine($crate) }
}
[IO.File]::WriteAllText("$root\licenses\rust-crates.txt", $out.ToString().Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding $false))
Write-Host "$($lines.Count) crates, $($texts.Count) distinct texts, $($bare.Count) without a file: $($bare -join ', ')"
